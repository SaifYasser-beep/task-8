let start = confirm("عايز تبدأ ولا تخليك في البيت احسن؟");

if (start) {
    let choice1 = prompt("انت يا بيه بسبب فضولك بدأنا الرحلة، وقدامك غابة فا تحب تخش أنهي: يمين ولا شمال؟");

    if (choice1 === "يمين") {
        let choice2 = prompt("شكلك بتعرف ربنا، ربنا يجعلنا من أهل اليمين.. بس كده إحنا قابلنا البشمهندس زياد وبيقولك فين التاسك، عملته ولا لا؟ (اكتب: عملته أو معملتوش)");

        if (choice2 === "عملته") {
            alert("عاش! البشمهندس هيعمل السيشن الجاية إجازة 🎉");
        }

        if (choice2 === "معملتوش") {
            alert("البشمهندس هينفخنا السيشن الجاية! ة 💥");
        }

        if (choice2 !== "عملته" && choice2 !== "معملتوش") {
            alert("اترددت في الإجابة فالبشمهندس طردك من الكورس!");
        }
    }

    if (choice1 === "شمال") {
        alert("دخلت الشمال كويس مش ها نقابل المهندس زياد! 💥");
    }

    if (choice1 !== "يمين" && choice1 !== "شمال") {
        alert("اختيار غير صحيح، انتهت اللعبة.");
    }
}

if (!start) {
    alert("قررت البقاء في المنزل أماناً لك!");
}